export function getPronunciation(text: string, targetLangCode: string): string {
  const clean = text.trim();
  if (!clean) return "";

  // Check direct lookup
  if (DICTIONARY_PRONUNCIATIONS[clean]) {
    return DICTIONARY_PRONUNCIATIONS[clean];
  }

  // Check lowercase lookup
  const lower = clean.toLowerCase();
  for (const [k, v] of Object.entries(DICTIONARY_PRONUNCIATIONS)) {
    if (k.toLowerCase() === lower) return v;
  }

  if (targetLangCode === "hi") {
    return generateHindiPhonetic(clean);
  } else if (targetLangCode === "es") {
    return generateSpanishPhonetic(clean);
  } else {
    return `\\${clean.toUpperCase()}\\`;
  }
}

function generateSpanishPhonetic(phrase: string): string {
  const words = phrase.split(/\s+/);
  const phoneticWords = words.map((word) => {
    let lower = word.toLowerCase()
      .replace(/ll/g, "y")
      .replace(/rr/g, "RR")
      .replace(/ch/g, "ch")
      .replace(/que/g, "kay")
      .replace(/qui/g, "kee")
      .replace(/ce/g, "say")
      .replace(/ci/g, "see")
      .replace(/ge/g, "hay")
      .replace(/gi/g, "hee")
      .replace(/j/g, "h")
      .replace(/ñ/g, "ny")
      .replace(/v/g, "b")
      .replace(/z/g, "s")
      .replace(/h/g, "");
    return lower.toUpperCase();
  });
  return `\\${phoneticWords.join(" ")}\\`;
}

function generateHindiPhonetic(phrase: string): string {
  const charMap: Record<string, string> = {
    "अ": "a", "आ": "aa", "इ": "i", "ई": "ee", "उ": "u", "ऊ": "oo",
    "ए": "ay", "ऐ": "ai", "ओ": "oh", "औ": "au",
    "क": "k", "ख": "kh", "ग": "g", "घ": "gh", "ङ": "ng",
    "च": "ch", "छ": "chh", "ज": "j", "झ": "jh", "ञ": "ny",
    "ट": "t", "ठ": "th", "ड": "d", "ढ": "dh", "ण": "n",
    "त": "t", "थ": "th", "द": "d", "ध": "dh", "न": "n",
    "प": "p", "फ": "ph", "ब": "b", "भ": "bh", "म": "m",
    "य": "y", "र": "r", "ल": "l", "व": "v", "श": "sh",
    "ष": "sh", "स": "s", "ह": "h",
    "ा": "AA", "ि": "i", "ी": "EE", "ु": "u", "ू": "OO",
    "े": "AY", "ै": "AI", "ो": "OH", "ौ": "AU", "ं": "n",
  };

  const words = phrase.split(/\s+/);
  const romanized = words.map((word) => {
    let result = "";
    for (const char of word) {
      if (charMap[char]) {
        result += charMap[char];
      } else if (/[a-zA-Z0-9]/.test(char)) {
        result += char;
      }
    }
    return result.length > 2 ? result.toUpperCase() : result;
  });

  return `\\${romanized.join(" ")}\\`;
}
